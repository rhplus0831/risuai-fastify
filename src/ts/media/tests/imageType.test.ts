import { expect, test } from 'vitest'
import { getImageType } from '../imageType'

test.each<[string, Uint8Array, ReturnType<typeof getImageType>]>([
  ['JPEG', new Uint8Array([0xff, 0xd8, 0x00, 0x00, 0xff, 0xd9]), 'JPEG'],
  ['PNG', new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), 'PNG'],
  ['GIF87a', new Uint8Array([0x47, 0x49, 0x46, 0x38, 0x37, 0x61]), 'GIF'],
  ['GIF89a', new Uint8Array([0x47, 0x49, 0x46, 0x38, 0x39, 0x61]), 'GIF'],
  ['BMP', new Uint8Array([0x42, 0x4d, 0x00, 0x00]), 'BMP'],
  ['AVIF', new Uint8Array([0x00, 0x00, 0x00, 0x00, 0x66, 0x74, 0x79, 0x70, 0x61, 0x76, 0x69, 0x66]), 'AVIF'],
  ['WEBP', new Uint8Array([0x52, 0x49, 0x46, 0x46, 0x00, 0x00, 0x00, 0x00, 0x57, 0x45, 0x42, 0x50]), 'WEBP'],
  ['an unrecognized format', new Uint8Array([0x00, 0x01, 0x02, 0x03]), 'Unknown'],
  ['an empty array', new Uint8Array([]), 'Unknown'],
])('detects %s', (_case, input, expected) => {
  expect(getImageType(input)).toBe(expected)
})
